"""
Purpose : S2-5 Store desk movement requests in PostgreSQL.

A movement request is saved in the desk_commands table as either
"accepted" or "failed". The table has a foreign key to desk(desk_id), so the
desk row has to exist before a command can be saved for it.
"""

import psycopg2

from Data.desk_repository import DatabaseError, get_database_connection

# The only two status values this application writes to desk_commands.status.
STATUS_ACCEPTED = "accepted"
STATUS_FAILED = "failed"
VALID_STATUSES = (STATUS_ACCEPTED, STATUS_FAILED)


def desk_exists(desk_id):
    """Return True if the desk is already stored in the desk table."""
    conn = get_database_connection()
    try:
        with conn, conn.cursor() as cursor:
            cursor.execute("SELECT 1 FROM desk WHERE desk_id = %s;", (desk_id,))
            return cursor.fetchone() is not None
    except psycopg2.Error as err:
        raise DatabaseError(f"Database operation failed: {err}") from None
    finally:
        conn.close()


def save_desk_identity(desk_record):
    """
    Insert the desk row (or update its name and manufacturer) WITHOUT saving
    a reading. Used when a movement is requested for a desk that has not been
    synchronised yet, so the command has a desk to point to.
    """
    config = desk_record["config"]
    conn = get_database_connection()
    try:
        with conn, conn.cursor() as cursor:
            cursor.execute(
                """
                INSERT INTO desk (desk_id, name, manufacturer)
                VALUES (%s, %s, %s)
                ON CONFLICT (desk_id) DO UPDATE
                SET name = EXCLUDED.name,
                    manufacturer = EXCLUDED.manufacturer;
                """,
                (desk_record["desk_id"], config["name"], config["manufacturer"]),
            )
    except psycopg2.Error as err:
        raise DatabaseError(f"Database operation failed: {err}") from None
    finally:
        conn.close()


def save_command(desk_id, target_position_mm, status):
    """
    Save one movement request and return its command_id.

    target_position_mm is the height that was REQUESTED (the table only allows
    positive values). status must be "accepted" or "failed".
    command_id and requested_at are generated by PostgreSQL.
    """
    if status not in VALID_STATUSES:
        raise ValueError(f"Command status must be one of {VALID_STATUSES}")

    conn = get_database_connection()
    try:
        with conn, conn.cursor() as cursor:
            cursor.execute(
                """
                INSERT INTO desk_commands (desk_id, target_position_mm, status)
                VALUES (%s, %s, %s)
                RETURNING command_id;
                """,
                (desk_id, target_position_mm, status),
            )
            return cursor.fetchone()[0]
    except psycopg2.Error as err:
        raise DatabaseError(f"Database operation failed: {err}") from None
    finally:
        conn.close()
